chars = [chr(c) for c in range(32, 127)]
missing = [c for c in chars if c not in G]
assert not missing, missing
data = []
for c in chars:
    for r in G[c]:
        v = 0
        for i, px in enumerate(r):
            if px == '#':
                v |= 0x80 >> i
        data.append(v)
assert len(data) == 95 * 8

out = sys.argv[1] if len(sys.argv) > 1 else None
lines = []
lines.append("// 8x8 ビットマップフォント（ASCII 32〜126、Fascon 1.0 の GUI デモ用に手作業でデザイン・CC0）")
lines.append("// 8x8 bitmap font (ASCII 32-126), hand-designed for the Fascon 1.0 GUI demo (CC0)")
lines.append("// 1 文字 8 バイト、各バイトの最上位ビットが左端 / 8 bytes per glyph, the MSB of each byte is the leftmost pixel")
lines.append("static FONT: [u8; 760] = [")
for k in range(0, len(data), 16):
    lines.append("    " + ", ".join("0x%02x" % b for b in data[k:k + 16]) + ",")
lines.append("];")
txt = "\n".join(lines) + "\n"
if out:
    open(out, "w").write(txt)
else:
    print(txt)
