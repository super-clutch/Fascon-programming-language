# 8x8 bitmap font for ASCII 32..126, designed by hand for the Fascon 1.0 GUI demo (public domain / CC0).
# Each glyph: 8 rows x 5 columns ('#' = on). Row 6 is the baseline row; row 7 is for descenders.
import sys

G = {}
def g(ch, rows):
    rows = rows.split()
    assert len(rows) == 8, (ch, len(rows))
    for r in rows:
        assert len(r) == 5, (ch, r)
    G[ch] = rows

